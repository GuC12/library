-- Apply in Supabase SQL Editor. Reports are submitted by signed-in readers;
-- review and resolution happen from the Supabase dashboard with an admin role.
create table if not exists public.content_reports (
  id bigint generated by default as identity primary key,
  reporter_id text not null,
  content_type text not null check (content_type in ('book')),
  content_id text not null,
  content_title text not null,
  reason text not null check (char_length(trim(reason)) between 1 and 1000),
  status text not null default 'open' check (status in ('open', 'reviewing', 'resolved', 'dismissed')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewer_note text
);

create index if not exists content_reports_open_created_idx
  on public.content_reports (created_at desc) where status = 'open';
create index if not exists content_reports_content_idx
  on public.content_reports (content_type, content_id, created_at desc);

alter table public.content_reports enable row level security;
revoke all on public.content_reports from anon, authenticated;
grant insert on public.content_reports to authenticated;
grant usage on sequence public.content_reports_id_seq to authenticated;
drop policy if exists "Signed-in readers can report content" on public.content_reports;
create policy "Signed-in readers can report content"
  on public.content_reports for insert to authenticated
  with check (
    reporter_id = (select auth.jwt() ->> 'sub')
    and char_length(trim(reason)) between 1 and 1000
    and content_type = 'book'
  );

-- No client read/update policy is granted: report details remain private to
-- database administrators and cannot be enumerated or resolved by reporters.
