import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const files = [
  'supabase-schema.sql',
  'supabase-secure-friend-reading.sql',
  'supabase-library-security.sql',
  'supabase-book-illustrations.sql',
  'supabase-content-reports.sql',
  'supabase-private-chat.sql',
  'supabase-reader-state.sql',
  'supabase-reader-rewards.sql',
  'supabase-reader-journey.sql',
];
const parts = await Promise.all(files.map(async file => {
  const sql = await readFile(new URL(file, root), 'utf8');
  return `-- SOURCE: ${file}\n${sql.replace(/^(begin|commit);\s*$/gmi, '')}`;
}));
await writeFile(new URL('supabase-setup.sql', root),
  '-- Generated by scripts/build-supabase-setup.mjs. Apply after enabling Clerk third-party auth.\n'
  + 'begin;\n' + parts.join('\n\n') + '\ncommit;\n');
console.log('Generated transactional supabase-setup.sql');
