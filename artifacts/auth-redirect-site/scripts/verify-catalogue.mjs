import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { gunzipSync } from 'node:zlib';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = file => readFile(path.join(root, file));
const json = async file => JSON.parse(await read(file));
const hash = data => createHash('sha256').update(data).digest('hex');
const manifests = await Promise.all(['catalogue', 'russian-classics', 'kazakh-classics', 'gutenberg'].map(name => json(`src/data/${name}.json`)));
const all = manifests.flat();
const publicCatalogue = await json('src/data/curated-books.json');
const [gutenbergProvenance, russianProvenance] = await Promise.all([
  json('public/books/gutenberg-provenance.json'), json('public/books/wikisource-provenance.json'),
]);
const pgById = new Map(gutenbergProvenance.map(item => [item.id + 100000, item]));
const ruById = new Map(russianProvenance.map(item => [item.bookId, item]));
const booksModule = (await read('src/data/books.ts')).toString();
assert.match(booksModule, /pages: SPECIAL_BOOK.pages.map/);
assert.match(booksModule, /text: specialReadablePages\[index\]/);
assert.match(booksModule, /MISS_SHOPAHOLIC_BOOK, \.\.\.sourcedEditionBooks/);
assert.match(booksModule, /import curatedBooks from '\.\/curated-books\.json'/);
assert.doesNotMatch(booksModule, /import (?:catalogue|gutenberg|russianClassics|kazakhClassics) from/);

const publicIds = new Set();
const visibleLanguages = { ru: 2, en: 0, kk: 0, zh: 0 };
const visibleCategories = new Map();
for (const book of publicCatalogue) {
  assert.ok(!publicIds.has(book.id), `Duplicate visible catalogue ID: ${book.id}`);
  publicIds.add(book.id);
  visibleLanguages[book.language]++;
  visibleCategories.set(book.category, (visibleCategories.get(book.category) || 0) + 1);
  assert.ok(['edition', 'library-original'].includes(book.coverKind), `${book.title}: visible cover type is unsupported`);
  if (book.coverKind === 'edition') {
    assert.ok(book.coverSourceUrl, `${book.title}: cover source missing`);
    assert.doesNotThrow(() => new URL(book.coverSourceUrl), `${book.title}: invalid cover source URL`);
  } else {
    assert.match(book.coverEdition || '', /project|catalogue cover|скан/i);
  }
  assert.ok(book.summary && !/Full text of|Полный текст произведения|Catalog source themes/i.test(book.summary), `${book.title}: summary is a placeholder`);
  assert.ok(book.coverImage.startsWith('books/covers/'), `${book.title}: cover must be a local image`);
  const cover = await read(`public/${book.coverImage}`);
  assert.ok(cover.length > (book.coverImage.endsWith('.svg') ? 500 : 2500), `${book.title}: cover file is missing or too small`);
  const isJpeg = cover[0] === 0xff && cover[1] === 0xd8 && cover[2] === 0xff;
  const isPng = cover.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]));
  const isWebp = cover.toString('ascii', 0, 4) === 'RIFF' && cover.toString('ascii', 8, 12) === 'WEBP';
  const isSvg = cover.toString('utf8', 0, 500).includes('<svg');
  assert.ok(isJpeg || isPng || isWebp || isSvg, `${book.title}: cover file is not a supported image`);
}
visibleCategories.set('Художественная литература', visibleCategories.get('Художественная литература') + 2);
assert.equal(publicCatalogue.length + 2, 413, 'The visible library must contain exactly 413 books.');
assert.deepEqual(visibleLanguages, { ru: 142, en: 268, kk: 2, zh: 1 }, 'Visible language totals changed.');
const russianBatch = await json('src/data/russian-batch-100.json');
assert.equal(russianBatch.length, 100, 'The Russian book batch must contain exactly 100 books.');
assert.ok(russianBatch.every(book => publicIds.has(book.id)), 'Every imported Russian book must be visible.');
assert.equal(visibleCategories.size, 16, 'All 16 reading categories must contain visible books.');
const excludedCoverIds = new Set((await json('src/data/generated-cover-exclusions.json')).ebookIds);
for (const book of publicCatalogue) {
  const ebookId = Number(book.coverImage.match(/gutenberg-edition-(\d+)\.jpg$/)?.[1]);
  assert.ok(!excludedCoverIds.has(ebookId), `${book.title}: autogenerated Gutenberg cover returned to the visible catalogue`);
}

const ids = new Set();
const titles = new Set();
const languages = { ru: 2, en: 0, kk: 0, zh: 0 };
const categories = new Map();
const covers = new Map();
let sourceBytes = 0;
for (const book of all) {
  assert.ok(!ids.has(book.id), `Duplicate book ID: ${book.id}`);
  ids.add(book.id);
  const normalizedTitle = `${book.language}|${book.title.normalize('NFKC').toLocaleLowerCase().replace(/[^\p{L}\p{N}]+/gu, '')}`;
  assert.ok(!titles.has(normalizedTitle), `Duplicate book title: ${book.title}`);
  titles.add(normalizedTitle);
  assert.ok(['ru', 'en', 'kk', 'zh'].includes(book.language), `${book.title}: unsupported language`);
  languages[book.language]++;
  categories.set(book.category, (categories.get(book.category) || 0) + 1);
  covers.set(book.coverKind, (covers.get(book.coverKind) || 0) + 1);
  for (const field of ['title', 'author', 'summary', 'sourceUrl', 'sourceName', 'sourceLicense', 'textPath', 'coverImage', 'coverKind']) {
    assert.ok(book[field], `${book.title}: missing ${field}`);
  }
  assert.doesNotThrow(() => new URL(book.sourceUrl), `${book.title}: invalid source URL`);
  if (book.coverImage.startsWith('https://')) assert.doesNotThrow(() => new URL(book.coverImage));
  else assert.ok((await read(`public/${book.coverImage}`)).length > 1000, `${book.title}: missing cover file`);
  if (book.coverKind === 'edition') assert.ok(book.coverSourceUrl, `${book.title}: edition cover source missing`);

  const pageFile = await read(`public/${book.textPath}`);
  const pages = book.textPath.endsWith('.gz') ? JSON.parse(gunzipSync(pageFile).toString('utf8')) : JSON.parse(pageFile.toString('utf8'));
  assert.ok(Array.isArray(pages), `${book.title}: page file must be an array`);
  assert.equal(pages.length, book.pageCount, `${book.title}: page count mismatch`);
  assert.ok(pages.length > 0, `${book.title}: no reading pages`);
  assert.ok(pages.every(page => typeof page.title === 'string' && page.kicker?.trim() && page.text?.trim()), `${book.title}: invalid page data`);
  if (book.id === 42070) {
    assert.match(pages.slice(0, 3).map(page => page.text).join(' '), /Бедные люди/u, 'Poor Folk text must match the book title.');
    assert.ok(pages.reduce((total, page) => total + page.text.length, 0) > 250000, 'Poor Folk must contain its complete text.');
  }
  if (book.id === 42575) {
    const fullText = pages.map(page => page.text).join(' ');
    assert.ok(fullText.length > 250000, 'The Gambler must contain the complete novel.');
    assert.ok(fullText.includes('\u0420\u0443\u043b\u0435\u0442'), 'The Gambler must contain its roulette narrative.');
  }
  if (book.id === 42383) {
    const fullText = pages.map(page => page.text).join(' ');
    assert.ok(fullText.startsWith(book.title), 'The Nest of the Gentry text must match its title.');
    assert.ok(fullText.length > 500000, 'The Nest of the Gentry must contain the complete novel.');
  }
  if (book.id === 42464) {
    const fullText = pages.map(page => page.text).join(' ');
    assert.ok(fullText.includes('1862'), 'Smoke must contain Turgenev\'s novel, not an unrelated work.');
    assert.ok(fullText.length > 300000, 'Smoke must contain the complete novel.');
  }
  if (book.id === 42576) {
    const fullText = pages.map(page => page.text).join(' ');
    assert.match(fullText, /Князь Мышкин/u, 'The Idiot must contain Prince Myshkin, not an unrelated short text.');
    assert.ok(pages.length > 1000, 'The Idiot must include the full four-part novel.');
  }
  const pg = pgById.get(book.id);
  const ru = ruById.get(book.id);
  if (book.id === 158585) {
    const fullText = pages.map(page => page.text).join('\n');
    const normalizedText = fullText.replace(/\s+/g, ' ');
    assert.ok(fullText.startsWith('THE PROPHET'), 'The Prophet must not start partway through the book.');
    assert.ok(fullText.length > 60000, 'The Prophet must contain the complete text, not only its later chapters.');
    assert.ok(normalizedText.includes('Almustafa, the chosen and the'), 'The Prophet must include its opening chapter.');
    assert.ok(normalizedText.includes('Farewell to you and the youth I have spent with you.'), 'The Prophet must include its final chapter.');
  }
  if (book.id === 31999) {
    assert.equal(book.title, 'Три сестры', 'The verified Chekhov edition should be present.');
    assert.match(book.coverLicense || '', /Public domain/i, 'The first-edition cover rights must be documented.');
    assert.match(book.coverEdition || '', /1901/, 'The cover must identify the matching 1901 edition.');
  }
  if (book.id === 31998) {
    assert.equal(book.title, 'Преступление и наказание', 'The verified 1867 Dostoevsky edition should be present.');
    assert.match(book.coverLicense || '', /Public domain/i, 'The first-edition cover rights must be documented.');
    assert.match(book.coverEdition || '', /1867/, 'The cover must identify the matching 1867 edition.');
  }
  if (book.id === 31997) {
    assert.equal(book.title, 'Война и мир', 'The verified 1912 Tolstoy edition should be present.');
    assert.match(book.coverLicense || '', /Public domain/i, 'The historical cover rights must be documented.');
    assert.match(book.coverEdition || '', /1912/, 'The cover must identify the 1912 edition.');
    assert.ok(ru && ru.characters > 2500000, 'All volumes and the epilogue should be archived.');
  }
  const sourceManifestRecord = all.find(item => item.id === book.id);
  const sourceArchivePath = book.sourceArchivePath || sourceManifestRecord?.sourceArchivePath;
  if (pg || ru) assert.ok(sourceArchivePath, `${book.title}: source archive path missing`);
  if (sourceArchivePath) {
    const source = await read(sourceArchivePath);
    sourceBytes += source.length;
    if (pg) {
      assert.equal(hash(source), pg.originalSha256, `${book.title}: Gutenberg source checksum mismatch`);
      const original = source.toString('utf8').replace(/\r\n/g, '\n');
      assert.match(original, /\*\*\* START OF (?:THE|THIS) PROJECT GUTENBERG EBOOK/i);
      assert.match(original, /FULL PROJECT GUTENBERG LICENSE/i);
    }
    if (ru) assert.equal(hash(source), ru.originalSha256, `${book.title}: Wikisource source checksum mismatch`);
  }
}

for (const category of ['Художественная литература', 'Классика', 'Поэзия', 'Детективы', 'Приключения', 'Фантастика', 'Фэнтези', 'Любовные романы', 'Историческая проза', 'Философия', 'Детская литература', 'Драма и пьесы', 'Путешествия', 'Познавательная литература', 'Казахская литература', 'Русская литература']) {
  assert.ok(categories.get(category), `Empty category: ${category}`);
}

